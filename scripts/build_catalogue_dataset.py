def generate_file():
    dest = Path(__file__).resolve().parent.parent / "rxshield" / "sources" / "medication_catalogue_data.py"
    
    code_lines = [
        '"""',
        'rxshield/sources/medication_catalogue_data.py',
        '',
        'Standardized Medication Catalogue Baseline Dataset',
        '==================================================',
        'Curated and verified from official U.S. National Library of Medicine (NLM / NIH)',
        'RxNorm clinical drug nomenclature and RxNav APIs.',
        '"""',
        '',
        'from __future__ import annotations',
        '',
        'from typing import Any',
        '',
        'RAW_CATALOGUE_DATA: list[dict[str, Any]] = ['
    ]

    for c in RAW_CONCEPTS:
        code_lines.append('    {')
        code_lines.append(f'        "drug_id": {repr(c["drug_id"])},')
        code_lines.append(f'        "rxcui": {repr(c["rxcui"])},')
        code_lines.append(f'        "name": {repr(c["name"])},')
        code_lines.append(f'        "generic_name": {repr(c["generic_name"])},')
        code_lines.append(f'        "brand_name": {repr(c["brand_name"])},')
        code_lines.append(f'        "term_type": {repr(c["term_type"])},')
        code_lines.append(f'        "dosage_form": {repr(c["dosage_form"])},')
        code_lines.append(f'        "strength": {repr(c["strength"])},')
        code_lines.append(f'        "synonyms": {repr(c["synonyms"])},')
        code_lines.append(f'        "is_combination": {repr(c["is_combination"])},')
        code_lines.append(f'        "therapeutic_category": {repr(c["therapeutic_category"])},')
        code_lines.append(f'        "status": {repr(c["status"])},')
        code_lines.append(f'        "active_ingredients": {repr(c["active_ingredients"])},')
        code_lines.append('    },')

    code_lines.append(']')
    code_lines.append('')

    content = '\n'.join(code_lines)
    dest.write_text(content, encoding='utf-8')
    print(f"Generated {dest} with {len(RAW_CONCEPTS)} concepts.")

if __name__ == "__main__":
    generate_file()
